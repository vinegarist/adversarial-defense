def latex_escape(value: str) -> str:
    """LaTeX特殊字符转义"""
    replacements = {
        "\\": r"\textbackslash{}",
        "&": r"\&",
        "%": r"\%",
        "_": r"\_",
        "#": r"\#",
        "{": r"\{",
        "}": r"\}",
        "~": r"\textasciitilde{}",
        "^": r"\textasciicircum{}",
    }
    out = str(value)
    for k, v in replacements.items():
        out = out.replace(k, v)
    return out


def is_number(s: str) -> bool:
    """检查是否为数字"""
    try:
        float(s)
        return True
    except (ValueError, TypeError):
        return False


def write_latex_table(
    headers: list[str],
    rows: list[list[Any]],
    caption: str,
    label: str,
    tex_path: Path,
    align: str | None = None,
) -> None:
    """生成LaTeX表格文件"""
    if align is None:
        align = "l" + "r" * (len(headers) - 1)

    lines = [
        "% -*- coding: utf-8 -*-",
        "% Auto-generated by export_to_thesis.py",
        r"\begin{table}[htbp]",
        r"  \centering",
        f"  \\caption{{{caption}}}",
        f"  \\label{{{label}}}",
        f"  \\begin{{tabular}}{{{align}}}",
        r"    \toprule",
    ]

    # 表头
    header_line = "    " + " & ".join([r"\textbf{" + latex_escape(h) + "}" for h in headers]) + r" \\"
    lines.append(header_line)
    lines.append(r"    \midrule")

    # 数据行
    for row in rows:
        vals = []
        for v in row:
            v = "" if v is None else str(v)
            if is_number(v):
                fv = float(v)
                v = f"{fv:.2f}" if abs(fv) >= 1 else f"{fv:.4f}".rstrip("0").rstrip(".")
            vals.append(latex_escape(v))
        lines.append("    " + " & ".join(vals) + r" \\")

    lines.extend([
        r"    \bottomrule",
        r"  \end{tabular}",
        r"\end{table}",
    ])

    tex_path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"  [生成表格] {tex_path}")


